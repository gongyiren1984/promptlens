#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const catalogPath = join(root, 'schemas', 'error-catalog.json');
const outputPath = join(root, 'packages', 'contracts', 'src', 'generated', 'error-catalog.ts');

const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'));
const familyDefaults = new Map(catalog.families.map((family) => [family.prefix, family]));

function exitCodeFor(entry) {
  if (entry.exitCode != null) return entry.exitCode;
  const family = familyDefaults.get(entry.family);
  if (family?.cliExitCode != null) return family.cliExitCode;
  return entry.retryable ? 10 : 11;
}

const entries = catalog.codes
  .map((entry) => ({
    code: entry.code,
    family: entry.family,
    retryable: Boolean(entry.retryable),
    scope: entry.scope,
    exitCode: exitCodeFor(entry),
    message: entry.message,
    remediation: entry.remediation ?? null,
  }))
  .sort((a, b) => a.code.localeCompare(b.code));

const lines = [];
lines.push('// AUTO-GENERATED by scripts/generate-contracts.js from schemas/error-catalog.json.');
lines.push('// Do not edit by hand. Run `npm run contracts:generate`.');
lines.push('');
lines.push('export interface ErrorCatalogEntry {');
lines.push('  family: string;');
lines.push('  retryable: boolean;');
lines.push('  scope: string;');
lines.push('  exitCode: number;');
lines.push('  message: string;');
lines.push('  remediation: string | null;');
lines.push('}');
lines.push('');
lines.push('export const ERROR_FAMILIES = ' + JSON.stringify(catalog.families, null, 2) + ' as const;');
lines.push('');
lines.push('export const ERROR_CODES = {');
for (const entry of entries) {
  const payload = {
    family: entry.family,
    retryable: entry.retryable,
    scope: entry.scope,
    exitCode: entry.exitCode,
    message: entry.message,
    remediation: entry.remediation,
  };
  lines.push(`  ${entry.code}: ${JSON.stringify(payload)},`);
}
lines.push('} as const;');
lines.push('');
lines.push('export type ErrorCode = keyof typeof ERROR_CODES;');
lines.push('');
lines.push('export function errorCatalogEntry(code: string): ErrorCatalogEntry | null {');
lines.push('  return (ERROR_CODES as Record<string, ErrorCatalogEntry>)[code] ?? null;');
lines.push('}');
lines.push('');
lines.push('export const ERROR_CODE_LIST: ErrorCode[] = Object.keys(ERROR_CODES) as ErrorCode[];');
lines.push('');
const output = `${lines.join('\n')}\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== output) {
    process.stderr.write('契约生成物与 schemas/error-catalog.json 不一致，请运行 npm run contracts:generate。\n');
    process.exit(1);
  }
  process.stdout.write('契约生成物已同步。\n');
} else {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, output, 'utf8');
  process.stdout.write(`已生成 ${outputPath}\n`);
}
