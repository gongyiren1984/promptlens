#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outputPath = join(root, 'apps', 'desktop', 'src', 'generated', 'notices.ts');

function npmNotices() {
  const lockPath = join(root, 'package-lock.json');
  if (!existsSync(lockPath)) return [];
  const lock = JSON.parse(readFileSync(lockPath, 'utf8'));
  const entries = [];
  for (const [key, value] of Object.entries(lock.packages ?? {})) {
    if (!key || value.dev || value.link) continue;
    const name = value.name ?? key.replace(/^node_modules\//, '').split('node_modules/').pop();
    if (!name) continue;
    entries.push({ name, version: value.version ?? '', license: value.license ?? 'UNKNOWN', ecosystem: 'npm' });
  }
  return entries;
}

function cargoNotices() {
  const lockPath = join(root, 'apps', 'desktop', 'src-tauri', 'Cargo.lock');
  if (!existsSync(lockPath)) return [];
  const registryRoot = join(homedir(), '.cargo', 'registry', 'src');
  let registries = [];
  try {
    registries = readdirSync(registryRoot).filter((name) => statSync(join(registryRoot, name)).isDirectory());
  } catch {
    return [];
  }
  const entries = [];
  for (const block of readFileSync(lockPath, 'utf8').split('[[package]]').slice(1)) {
    const name = /^\s*name\s*=\s*"([^"]+)"/m.exec(block)?.[1];
    const version = /^\s*version\s*=\s*"([^"]+)"/m.exec(block)?.[1];
    if (!name || !version) continue;
    let license = 'UNKNOWN';
    for (const registry of registries) {
      const manifest = join(registryRoot, registry, `${name}-${version}`, 'Cargo.toml');
      if (!existsSync(manifest)) continue;
      const text = readFileSync(manifest, 'utf8');
      const declared = /^\s*license\s*=\s*"([^"]+)"/m.exec(text)?.[1];
      if (declared) license = declared;
      else if (/^\s*license-file\s*=/m.test(text)) license = 'See license file';
      break;
    }
    entries.push({ name, version, license, ecosystem: 'cargo' });
  }
  return entries;
}

const extras = [
  { name: 'Node.js', version: process.versions.node, license: 'MIT', ecosystem: 'runtime' },
  { name: 'SQLite', version: 'bundled', license: 'Public Domain', ecosystem: 'runtime' },
];

const byKey = new Map();
for (const entry of [...npmNotices(), ...cargoNotices(), ...extras]) {
  const key = `${entry.ecosystem}:${entry.name}@${entry.version}`;
  if (!byKey.has(key)) byKey.set(key, entry);
}
const entries = [...byKey.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version) || a.ecosystem.localeCompare(b.ecosystem));

const lines = [];
lines.push('// AUTO-GENERATED by scripts/generate-notices.js from package-lock.json 与 Cargo.toml。');
lines.push('// Do not edit by hand. Run `npm run notices:generate`.');
lines.push('');
lines.push('export interface NoticeEntry {');
lines.push('  name: string;');
lines.push('  version: string;');
lines.push('  license: string;');
lines.push('  ecosystem: string;');
lines.push('}');
lines.push('');
lines.push('export const NOTICES: NoticeEntry[] = ' + JSON.stringify(entries, null, 2) + ';');
lines.push('');
lines.push('export const NOTICE_COUNT = NOTICES.length;');
lines.push('');
const output = `${lines.join('\n')}\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== output) {
    process.stderr.write('第三方许可清单与依赖不一致，请运行 npm run notices:generate。\n');
    process.exit(1);
  }
  process.stdout.write('第三方许可清单已同步。\n');
} else {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, output, 'utf8');
  process.stdout.write(`已生成 ${outputPath}（${entries.length} 项）\n`);
}
